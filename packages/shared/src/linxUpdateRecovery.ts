const decodeManifest = Schema.decodeUnknownSync(LinxUpdateRecoveryManifest);
type Root = "home" | "userData" | "managedReferences";

function inside(root: string, candidate: string): boolean {
  const relative = path.relative(root, candidate);
  return (
    relative === "" ||
    (!path.isAbsolute(relative) && relative !== ".." && !relative.startsWith(`..${path.sep}`))
  );
}

/** Existing ancestors must be real directories; system parent aliases are canonicalized. */
export async function canonicalLinxDataPath(input: string): Promise<string> {
  const absolute = path.resolve(input);
  const parent = await fs.realpath(path.dirname(absolute));
  const result = path.join(parent, path.basename(absolute));
  const stat = await fs.lstat(result).catch((error: NodeJS.ErrnoException) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (stat && (!stat.isDirectory() || stat.isSymbolicLink()))
    throw new Error(`Not a real data directory: ${input}`);
  return result;
}

function assertSeparate(paths: readonly string[]): void {
  for (let i = 0; i < paths.length; i++) {
    for (let j = i + 1; j < paths.length; j++) {
      if (inside(paths[i]!, paths[j]!) || inside(paths[j]!, paths[i]!)) {
        throw new Error("Recovery and data roots must be disjoint");
      }
    }
  }
}

function excluded(root: Root, relative: string): boolean {
  const segments = relative.split("/");
  // Only documented reconstructable runtime artifacts. Worktrees (including ignored files),
  // expert assets, secrets, attachments, SQLite WAL and browser IndexedDB are unique data.
  if (root === "userData")
    return (
      segments.length === 1 &&
      [
        "Cache",
        "Code Cache",
        "GPUCache",
        "DawnGraphiteCache",
        "DawnWebGPUCache",
        "ShaderCache",
        "GrShaderCache",
        "SingletonLock",
        "SingletonCookie",
        "SingletonSocket",
        "DevToolsActivePort",
        "linx-updater",
        "linx-update-staging",
        "linx-update-check.json",
        "pending-update-install.json",
      ].includes(relative)
    );
  return (
    /^(?:userdata|dev)\/(?:state\.sqlite\.lifecycle-lock(?:$|\/|\.(?:reaper|acquiring|released|stale)(?:\.|\/|$))|logs(?:\/|$))/u.test(
      relative,
    ) ||
    (segments.length === 1 && ["linx-updater", "linx-update-recovery"].includes(relative))
  );
}

function unchanged(a: Stats, b: Stats): boolean {
  return (
    a.dev === b.dev &&
    a.ino === b.ino &&
    a.size === b.size &&
    a.mtimeMs === b.mtimeMs &&
    a.ctimeMs === b.ctimeMs &&
    a.mode === b.mode
  );
}
/** Only direct aliases generated by codexProcessEnv are reconstructable.
 * Real overlay files/directories are always inventoried, including private auth.
 * The provider rebuilds omitted links on its next launch; recovery never reads
 * or copies external provider state and never restores an external write alias.
 */
async function codexOverlayAliasPolicy(home: string): Promise<Map<string, readonly string[]>> {
  const base = resolveBaseCodexHomePath(process.env);
  let settings: unknown = {};
  const userdata = path.join(home, "userdata");
  const directory = await fs.lstat(userdata).catch((error: NodeJS.ErrnoException) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (directory?.isDirectory() && !directory.isSymbolicLink()) {
    const handle = await fs
      .open(path.join(userdata, "settings.json"), constants.O_RDONLY | constants.O_NOFOLLOW)
      .catch((error: NodeJS.ErrnoException) => {
        if (error.code === "ENOENT") return null;
        throw error;
      });
    if (handle) {
      try {
        if (!(await handle.stat()).isFile()) throw new Error("Unsafe provider settings file");
        const parsed: unknown = JSON.parse(await handle.readFile("utf8"));
        settings =
          parsed && typeof parsed === "object" && "settings" in parsed ? parsed.settings : parsed;
      } finally {
        await handle.close();
      }
    }
  }
  const policies = new Map<string, readonly string[]>();
  const add = (source: string, accountId?: string, shadow?: string, dedicated = false) => {
    const accountSegment = resolveCodexHomeOverlayAccountSegment({
      homePath: source,
      ...(accountId !== undefined ? { accountId } : {}),
      ...(shadow !== undefined ? { shadowHomePath: shadow } : {}),
    });
    const overlay = path
      .relative(
        home,
        resolveSynaraCodexHomeOverlayPath({ SYNARA_HOME: home }, source, accountSegment),
      )
      .split(path.sep)
      .join("/");
    const fixedOverlay = path
      .relative(
        home,
        resolveSynaraCodexHomeOverlayPath({ SYNARA_HOME: home }, source, accountSegment, true),
      )
      .split(path.sep)
      .join("/");
    // Empty private source means an account's own real auth must not be
    // replaced with the default account's credentials.
    const privateSource = shadow ?? (accountSegment === undefined || dedicated ? source : "");
    policies.set(overlay, [source, privateSource]);
    policies.set(fixedOverlay, [source, privateSource]);
  };
  add(base);
  const decoded = Schema.decodeUnknownSync(ServerSettings)(settings);
  const providerInstances = { ...decoded.providerInstances };
  for (const [instanceId, instance] of Object.entries(providerInstances)) {
    if (instance.driver !== "codex" || !instance.environment) continue;
    const environment = await Promise.all(
      instance.environment.map(async (variable) => {
        if (
          variable.name.trim() !== "CODEX_HOME" ||
          !variable.sensitive ||
          variable.valueRedacted !== true
        )
          return variable;
        const secret = await readServerSecretFile(
          resolveServerSecretPath(
            path.join(userdata, "secrets"),
            providerEnvironmentSecretName({ instanceId, name: variable.name }),
          ),
        );
        const { valueRedacted: _valueRedacted, ...materialized } = variable;
        return { ...materialized, value: secret ? new TextDecoder().decode(secret) : "" };
      }),
    );
    providerInstances[instanceId] = { ...instance, environment };
  }
  for (const instance of deriveProviderInstances({ ...decoded, providerInstances })) {
    if (instance.driver !== "codex") continue;
    const options = providerStartOptionsFromInstance(instance)?.codex;
    const environment = { CODEX_HOME: options?.environment?.CODEX_HOME?.trim() || base };
    const ambient = resolveBaseCodexHomePath(environment);
    const source = resolveBaseCodexHomePath(environment, options?.homePath);
    add(
      source,
      options?.accountId?.trim(),
      options?.shadowHomePath?.trim()
        ? resolveBaseCodexHomePath(environment, options.shadowHomePath)
        : undefined,
      Boolean(options?.homePath?.trim()) && path.resolve(source) !== path.resolve(ambient),
    );
  }
  return policies;
}

function isRegenerableCodexAlias(
  relative: string,
  target: string,
  policies: ReadonlyMap<string, readonly string[]>,
): boolean {
  const directory = path.posix.dirname(relative);
  const policy = policies.get(directory);
  if (!policy) return false;
  const name = path.posix.basename(relative);
  // config.toml is generated as a real file, not an alias. SQLite state and
  // ownership markers are explicitly excluded by the provider's linker.
  if (
    name === "config.toml" ||
    /^.+\.sqlite(?:-(?:wal|shm|journal))?$/u.test(name) ||
    /^synara-shared-continuation-v[12]\.json$/u.test(name) ||
    name.startsWith(".synara-shared-continuation-v1.lock") ||
    (directory.endsWith(`/${SYNARA_CODEX_HOME_FIXED_EXPERT_DIR}`) &&
      (name === "skills" || name === "plugins"))
  )
    return false;
  const source = name === "auth.json" || name === "models_cache.json" ? policy[1] : policy[0];
  return Boolean(source) && target === path.resolve(source!, name);
}

async function transferFile(
  source: string,
  destination?: string,
): Promise<{ size: number; sha256: string }> {
  const before = await fs.lstat(source);
  if (!before.isFile() || before.isSymbolicLink()) throw new Error(`Not a regular file: ${source}`);
  const input = await fs.open(source, constants.O_RDONLY | constants.O_NOFOLLOW);
  let output: fs.FileHandle | undefined;
  try {
    if (!unchanged(before, await input.stat())) throw new Error(`Input changed: ${source}`);
    if (destination) output = await fs.open(destination, "wx", before.mode & 0o777);
    const hash = createHash("sha256");
    const buffer = Buffer.allocUnsafe(Math.min(1024 * 1024, Math.max(1, before.size)));
    let size = 0;
    for (;;) {
      const { bytesRead } = await input.read(buffer, 0, buffer.length, null);
      if (bytesRead === 0) break;
      const chunk = buffer.subarray(0, bytesRead);
      hash.update(chunk);
      if (output) {
        let offset = 0;
        while (offset < bytesRead) {
          const { bytesWritten } = await output.write(chunk, offset, bytesRead - offset);
          if (bytesWritten === 0) throw new Error("Recovery write made no progress");
          offset += bytesWritten;
        }
      }
      size += bytesRead;
    }
    if (
      size !== before.size ||
      !unchanged(before, await input.stat()) ||
      !unchanged(before, await fs.lstat(source))
    ) {
      throw new Error(`Input changed during recovery: ${source}`);
    }
    if (output) {
      await output.chmod(before.mode & 0o777);
      await output.sync();
    }
    return { size, sha256: hash.digest("hex") };
  } finally {
    await input.close();
    await output?.close();
  }
}

async function inventory(
  root: Root,
  rootPath: string,
  skipRuntime: boolean,
  allowMissing = false,
): Promise<LinxUpdateRecoveryEntry[]> {
  const entries: LinxUpdateRecoveryEntry[] = [];
  if (allowMissing) {
    const stat = await fs.lstat(rootPath).catch((error: NodeJS.ErrnoException) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    if (stat === null)
      return [
        { root, path: "", kind: "directory", mode: 0o700, size: 0, sha256: null, linkTarget: null },
      ];
  }
  let overlayAliases: Map<string, readonly string[]> | undefined;
  async function visit(relative: string): Promise<void> {
    if (relative !== "" && skipRuntime && excluded(root, relative)) return;
    const absolute = path.join(rootPath, relative);
    const before = await fs.lstat(absolute);
    if (
      skipRuntime &&
      relative !== "" &&
      !relative.includes("/") &&
      relative !== "worktrees" &&
      before.isDirectory()
    ) {
      const oldManifestPath = path.join(absolute, LINX_UPDATE_RECOVERY_MANIFEST_FILE_NAME);
      const oldManifest = await fs.lstat(oldManifestPath).catch((error: NodeJS.ErrnoException) => {
        if (error.code === "ENOENT") return null;
        throw error;
      });
      if (oldManifest !== null) {
        if (
          !oldManifest.isFile() ||
          oldManifest.isSymbolicLink() ||
          oldManifest.size > LINX_UPDATE_RECOVERY_MANIFEST_MAX_BYTES
        ) {
          throw new Error("Nested recovery set has an unsafe manifest");
        }
        const known = [
          "home",
          LINX_UPDATE_RECOVERY_MANIFEST_FILE_NAME,
          "userData",
          "managedReferences",
        ];
        if ((await fs.readdir(absolute)).some((name) => !known.includes(name))) {
          throw new Error(
            "Nested recovery set contains unknown unique files; move it outside the data roots before snapshotting",
          );
        }
        const handle = await fs.open(oldManifestPath, constants.O_RDONLY | constants.O_NOFOLLOW);
        try {
          decodeManifest(JSON.parse(await handle.readFile("utf8")));
        } finally {
          await handle.close();
        }
        return; // Never recursively include previous recovery sets.
      }
    }
    const mode = before.mode & 0o777;
    if (before.isSymbolicLink()) {
      const rawTarget = await fs.readlink(absolute);
      const resolvedTarget = path.resolve(path.dirname(absolute), rawTarget);
      if (
        root === "home" &&
        skipRuntime &&
        relative.startsWith(`${SYNARA_CODEX_HOME_OVERLAY_DIR}/`) &&
        !inside(rootPath, resolvedTarget)
      ) {
        overlayAliases ??= await codexOverlayAliasPolicy(rootPath);
        if (isRegenerableCodexAlias(relative, resolvedTarget, overlayAliases)) {
          if (!unchanged(before, await fs.lstat(absolute)))
            throw new Error(`Link changed during recovery: ${absolute}`);
          return;
        }
      }
      if (!rawTarget || (!path.isAbsolute(rawTarget) && !inside(rootPath, resolvedTarget))) {
        throw new Error(`Escaping recovery link: ${absolute}`);
      }
      // Lexical containment is insufficient when an intermediate link escapes.
      const canonicalTarget = await fs.realpath(absolute);
      if (!inside(rootPath, canonicalTarget))
        throw new Error(`Escaping recovery link: ${absolute}`);
      if (!unchanged(before, await fs.lstat(absolute)))
        throw new Error(`Link changed during recovery: ${absolute}`);
      // Absolute app-owned links are made relative so the restored home never
      // aliases or keeps writing the historical source root.
      const linkTarget = path.isAbsolute(rawTarget)
        ? path.relative(path.dirname(absolute), canonicalTarget) || "."
        : rawTarget;
      entries.push({
        root,
        path: relative,
        kind: "symlink",
        mode,
        size: 0,
        sha256: null,
        linkTarget,
      });
    } else if (before.isDirectory()) {
      entries.push({
        root,
        path: relative,
        kind: "directory",
        mode,
        size: 0,
        sha256: null,
        linkTarget: null,
      });
      for (const name of (await fs.readdir(absolute)).sort())
        await visit(relative ? `${relative}/${name}` : name);
      if (!unchanged(before, await fs.lstat(absolute)))
        throw new Error(`Directory changed during recovery: ${absolute}`);
    } else if (before.isFile()) {
      entries.push({
        root,
        path: relative,
        kind: "file",
        mode,
        ...(await transferFile(absolute)),
        linkTarget: null,
      });
    } else throw new Error(`Special file in recovery input: ${absolute}`);
    if (entries.length > LINX_UPDATE_RECOVERY_MAX_ENTRIES)
      throw new Error("Recovery entry limit exceeded");
  }
  await visit("");
  return entries;
}

function sameInventory(
  a: readonly LinxUpdateRecoveryEntry[],
  b: readonly LinxUpdateRecoveryEntry[],
): boolean {
  return JSON.stringify(a) === JSON.stringify(b);
}

async function requireSpace(
  directory: string,
  entries: readonly LinxUpdateRecoveryEntry[],
): Promise<void> {
  const required = entries.reduce(
    (total, entry) => total + BigInt(entry.size) + 4096n,
    64n * 1024n * 1024n,
  );
  const stat = await fs.statfs(directory, { bigint: true });
  if (stat.bavail * stat.bsize < required)
    throw Object.assign(new Error("Insufficient space for verified recovery data"), {
      code: "ENOSPC",
    });
}

async function copyEntries(
  entries: readonly LinxUpdateRecoveryEntry[],
  from: Partial<Record<Root, string>>,
  to: Partial<Record<Root, string>>,
): Promise<void> {
  for (const entry of entries) {
    const target = path.join(to[entry.root]!, entry.path);
    if (entry.kind === "directory") {
      if (entry.path !== "") await fs.mkdir(target, { mode: 0o700 });
    } else if (entry.kind === "symlink") await fs.symlink(entry.linkTarget!, target);
    else {
      const actual = await transferFile(path.join(from[entry.root]!, entry.path), target);
      if (actual.size !== entry.size || actual.sha256 !== entry.sha256)
        throw new Error(`Recovery input hash changed: ${entry.path}`);
    }
  }
  // Delay restrictive directory modes until all children exist.
  for (const entry of [...entries].reverse()) {
    if (entry.kind === "directory") {
      const target = path.join(to[entry.root]!, entry.path);
      await fs.chmod(target, entry.mode);
      await syncDirectoryEntry(target);
    }
  }
}

async function copyVerifiedDirectory(source: string, target: string): Promise<void> {
  const entries = await inventory("managedReferences", source, false);
  if (entries.some((entry) => entry.kind === "symlink"))
    throw new Error("Managed Git metadata contains a link outside its exact registration");
  await requireSpace(path.dirname(target), entries);
  await fs.mkdir(target, { mode: 0o700 });
  await copyEntries(entries, { managedReferences: source }, { managedReferences: target });
  if (
    !sameInventory(entries, await inventory("managedReferences", source, false)) ||
    !sameInventory(entries, await inventory("managedReferences", target, false))
  )
    throw new Error("Managed Git metadata changed during its verified copy");
}

async function copyVerifiedFile(source: string, target: string): Promise<void> {
  const copied = await transferFile(source, target);
  const actual = await transferFile(target);
  if (copied.size !== actual.size || copied.sha256 !== actual.sha256)
    throw new Error("Managed metadata file copy hash mismatch");
}

/** Caller must hold the source's offline profile/DB ownership; live Chromium requires logical export. */
export async function snapshotLinxOfflineUserData(input: {
  userDataPath: string;
  snapshotDirectoryPath: string;
}): Promise<void> {
  const source = await canonicalLinxDataPath(input.userDataPath);
  const target = await canonicalLinxDataPath(input.snapshotDirectoryPath);
  assertSeparate([source, target]);
  const entries = await inventory("userData", source, true, true);
  await requireSpace(path.dirname(target), entries);
  await fs.mkdir(target, { mode: 0o700 });
  await copyEntries(
    entries,
    { home: source, userData: source },
    { home: target, userData: target },
  );
  if (
    !sameInventory(entries, await inventory("userData", source, true, true)) ||
    !sameInventory(entries, await inventory("userData", target, false))
  )
    throw new Error("Offline profile changed during snapshot");
  await syncDirectoryEntry(path.dirname(target));
}

export async function createLinxUpdateRecoverySet(input: {
  recoveryDirectoryPath: string;
  homePath: string;
  userDataPath: string;
  attemptId: string;
  sourceVersion: string;
  /** Immutable prepared export, required instead of copying a live Chromium database. */
  userDataSnapshotPath?: string;
  userDataSnapshotFormat?: "offline-profile" | "portable-app-storage";
}): Promise<LinxUpdateRecoveryManifest> {
  const recovery = await canonicalLinxDataPath(input.recoveryDirectoryPath);
  const home = await canonicalLinxDataPath(input.homePath);
  const userData = await canonicalLinxDataPath(input.userDataPath);
  const profileSource =
    input.userDataSnapshotPath === undefined
      ? userData
      : await canonicalLinxDataPath(input.userDataSnapshotPath);
  assertSeparate(
    input.userDataSnapshotPath === undefined
      ? [recovery, home, userData]
      : [recovery, home, userData, profileSource],
  );
  if (input.userDataSnapshotPath === undefined) {
    const singleton = await fs
      .lstat(path.join(userData, "SingletonLock"))
      .catch((error: NodeJS.ErrnoException) => {
        if (error.code === "ENOENT") return null;
        throw error;
      });
    if (singleton)
      throw new Error(
        "Raw Chromium profile recovery requires an offline, unlocked profile or portable export",
      );
  }
  // Publish no manifest until every filesystem and external-reference component verifies.
  await requireSpace(path.dirname(recovery), []);
  // Preserve unpublished partial copies if the source changes: they may contain
  // the last surviving bytes. Only a fully verified manifest authorizes use.
  await fs.mkdir(recovery, { mode: 0o700 });
  const capsule = path.join(recovery, "managedReferences");
  const managedRepositories = await captureLinxManagedReferences({
    homePath: home,
    capsuleDirectoryPath: capsule,
    copyDirectory: copyVerifiedDirectory,
    copyFile: copyVerifiedFile,
  });
  const dataEntries = [
    ...(await inventory("home", home, true, true)),
    ...(await inventory("userData", profileSource, true, true)),
  ];
  const entries = managedRepositories.length
    ? [...dataEntries, ...(await inventory("managedReferences", capsule, false))]
    : dataEntries;
  const manifest = decodeManifest({
    schemaVersion: 1,
    attemptId: input.attemptId,
    sourceVersion: input.sourceVersion,
    createdAt: new Date().toISOString(),
    homePath: home,
    userDataPath: userData,
    managedRepositories,
    userDataFormat:
      input.userDataSnapshotPath === undefined
        ? "offline-profile"
        : (input.userDataSnapshotFormat ?? "portable-app-storage"),
    entries,
  });
  await requireSpace(path.dirname(recovery), entries);
  await fs.mkdir(path.join(recovery, "home"), { mode: 0o700 });
  await fs.mkdir(path.join(recovery, "userData"), { mode: 0o700 });
  await copyEntries(
    dataEntries,
    { home, userData: profileSource },
    { home: path.join(recovery, "home"), userData: path.join(recovery, "userData") },
  );
  if (
    !sameInventory(dataEntries, [
      ...(await inventory("home", home, true, true)),
      ...(await inventory("userData", profileSource, true, true)),
    ])
  ) {
    throw new Error("Recovery source changed while copying");
  }
  await preflightLinxManagedReferenceRestore(capsule, managedRepositories, {
    sourceHomePath: home,
    snapshotHomePath: path.join(recovery, "home"),
  });
  const text = `${JSON.stringify(manifest)}\n`;
  if (Buffer.byteLength(text) > LINX_UPDATE_RECOVERY_MANIFEST_MAX_BYTES)
    throw new Error("Recovery manifest too large");
  const handle = await fs.open(
    path.join(recovery, LINX_UPDATE_RECOVERY_MANIFEST_FILE_NAME),
    "wx",
    0o600,
  );
  try {
    await handle.writeFile(text);
    await handle.sync();
  } finally {
    await handle.close();
  }
  await syncDirectoryEntry(recovery);
  await syncDirectoryEntry(path.dirname(recovery));
  return verifyLinxUpdateRecoverySet(recovery);
}

export async function verifyLinxUpdateRecoverySet(
  recoveryDirectoryPath: string,
): Promise<LinxUpdateRecoveryManifest> {
  const recovery = await canonicalLinxDataPath(recoveryDirectoryPath);
  const manifestPath = path.join(recovery, LINX_UPDATE_RECOVERY_MANIFEST_FILE_NAME);
  const handle = await fs.open(manifestPath, constants.O_RDONLY | constants.O_NOFOLLOW);
  let manifest: LinxUpdateRecoveryManifest;
  try {
    const stat = await handle.stat();
    if (!stat.isFile() || stat.size > LINX_UPDATE_RECOVERY_MANIFEST_MAX_BYTES)
      throw new Error("Invalid recovery manifest file");
    manifest = decodeManifest(JSON.parse(await handle.readFile("utf8")));
  } finally {
    await handle.close();
  }
  const expected = [
    "home",
    LINX_UPDATE_RECOVERY_MANIFEST_FILE_NAME,
    "userData",
    ...(manifest.managedRepositories.length ? ["managedReferences"] : []),
  ];
  if (JSON.stringify((await fs.readdir(recovery)).sort()) !== JSON.stringify(expected.sort())) {
    throw new Error("Unexpected recovery-set contents");
  }
  const home = await canonicalLinxDataPath(path.join(recovery, "home"));
  const userData = await canonicalLinxDataPath(path.join(recovery, "userData"));
  const actual = [
    ...(await inventory("home", home, false)),
    ...(await inventory("userData", userData, false)),
    ...(manifest.managedRepositories.length
      ? await inventory("managedReferences", path.join(recovery, "managedReferences"), false)
      : []),
  ];
  if (!sameInventory(manifest.entries, actual))
    throw new Error("Recovery inventory, modes or content hash mismatch");
  await verifyLinxManagedReferenceCapsuleBindings(
    path.join(recovery, "managedReferences"),
    manifest.managedRepositories,
    { sourceHomePath: manifest.homePath, snapshotHomePath: home },
  );
  return manifest;
}

export async function restoreLinxUpdateRecoverySetToEmptyTargets(input: {
  recoveryDirectoryPath: string;
  homePath: string;
  userDataPath: string;
}): Promise<void> {
  const manifest = await verifyLinxUpdateRecoverySet(input.recoveryDirectoryPath);
  const recovery = await canonicalLinxDataPath(input.recoveryDirectoryPath);
  const home = await canonicalLinxDataPath(input.homePath);
  const userData = await canonicalLinxDataPath(input.userDataPath);
  assertSeparate([recovery, home, userData]);
  // Check BOTH before modifying either. A partial failed restore remains visibly nonempty.
  for (const target of [home, userData]) {
    const entries = await fs.readdir(target).catch((error: NodeJS.ErrnoException) => {
      if (error.code === "ENOENT") return [];
      throw error;
    });
    if (entries.length) throw new Error(`Recovery target is not empty: ${target}`);
    await requireSpace(path.dirname(target), manifest.entries);
  }
  const capsule = path.join(recovery, "managedReferences");
  const context = {
    sourceHomePath: manifest.homePath,
    snapshotHomePath: path.join(recovery, "home"),
  };
  await preflightLinxManagedReferenceRestore(capsule, manifest.managedRepositories, context);
  const dataEntries = manifest.entries.filter((entry) => entry.root !== "managedReferences");
  for (const target of [home, userData]) {
    // rmdir refuses a symlink or a raced nonempty target; mkdir reserves an
    // absent root exclusively instead of following a contender's directory.
    await fs.rmdir(target).catch((error: NodeJS.ErrnoException) => {
      if (error.code !== "ENOENT") throw error;
    });
    await fs.mkdir(target, { mode: 0o700 });
  }
  await copyEntries(
    dataEntries,
    { home: path.join(recovery, "home"), userData: path.join(recovery, "userData") },
    { home, userData },
  );
  const restored = [
    ...(await inventory("home", home, false)),
    ...(await inventory("userData", userData, false)),
  ];
  if (!sameInventory(dataEntries, restored))
    throw new Error("Restored recovery inventory mismatch");
  await restoreLinxManagedReferences({
    capsuleDirectoryPath: capsule,
    repositories: manifest.managedRepositories,
    copyDirectory: copyVerifiedDirectory,
    copyFile: copyVerifiedFile,
    ...context,
  });
  await syncDirectoryEntry(path.dirname(home));
  await syncDirectoryEntry(path.dirname(userData));
}
